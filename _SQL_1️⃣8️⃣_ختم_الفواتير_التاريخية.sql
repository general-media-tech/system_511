-- المشكلة (كشفها الفاحص العميق):
--   IMP-2026-0002 حالتها «arrived» لكن transferred ليست true.
--   السبب: رُحِّلت **قبل** إضافة أعمدة حالة الترحيل (نمط P1)، فبقيت بلا ختم.
--   الخطر: أي ترحيل لاحق لن يجد الختم ⇒ يضيف المخزون **مرة ثانية** ⇒ مضاعفة.
--
--   ملاحظة مهمّة: الكود الجديد يمنع المضاعفة عبر سجلّ الاستلام، لكن البيانات
--   التاريخية تبقى ملغومة حتى تُختم. هذا الملف يختمها.
