-- ① استعرض قبل التعديل (شغّل هذا أولاً لترى ما سيتأثّر)
select inv_number, status, transferred, transferred_at, items_count, total_qty
from import_log
where status = 'arrived' and (transferred is distinct from true)
order by inv_number;

-- ② الختم: كل فاتورة «واصلة» بلا ختم تُعتبر مُرحّلة فعلاً (فحالتها تقول ذلك)
update import_log
set transferred    = true,
    transferred_at = coalesce(transferred_at, updated_at, created_at, now()),
    transferred_by = coalesce(transferred_by, 'ختم تاريخي 2026-08-23')
where status = 'arrived'
  and (transferred is distinct from true);

-- ③ تحقّق بعد التعديل — يجب أن يعيد صفر صفوف
select count(*) as "فواتير_واصلة_بلا_ختم"
from import_log
where status = 'arrived' and (transferred is distinct from true);

-- ═══════════════════════════════════════════════════════════════════════════
-- 🔎 إضافي: الباركودات المكرّرة (كشفها الفاحص أيضاً — 5 حالات)
--    لا تُحذف تلقائياً: التكرار قد يكون منتجين مختلفين أُعطيا الباركود نفسه
--    خطأً، وحذف أحدهما يفقد بياناته. استعرضها وقرّر يدوياً.
-- ═══════════════════════════════════════════════════════════════════════════
select barcode, count(*) as "عدد", string_agg(name, ' | ') as "الأسماء",
       string_agg(id::text, ' | ') as "المعرّفات"
from products
where barcode is not null and btrim(barcode) <> ''
group by barcode
having count(*) > 1
order by count(*) desc;
